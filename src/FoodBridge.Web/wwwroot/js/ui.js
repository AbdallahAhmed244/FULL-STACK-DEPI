const toastArDict = toastI18n.enToAr;

function showToast(title, message, type = 'info') {
    const container = document.getElementById('toastContainer');
    if (!container) return;

    const isAr = currentLang === 'ar';
    let finalTitle = title;
    let finalMsg = message;

    if (title && typeof title === 'object') {
        finalTitle = isAr ? (title.ar || title.en) : (title.en || title.ar);
    }
    if (message && typeof message === 'object') {
        finalMsg = isAr ? (message.ar || message.en) : (message.en || message.ar);
    }

    if (isAr) {
        if (typeof finalTitle === 'string' && toastI18n.enToAr[finalTitle]) {
            finalTitle = toastI18n.enToAr[finalTitle];
        }
        if (typeof finalMsg === 'string') {
            if (toastI18n.enToAr[finalMsg]) {
                finalMsg = toastI18n.enToAr[finalMsg];
            } else if (finalMsg.startsWith('Signed in as ')) {
                finalMsg = 'تم تسجيل الدخول باسم ' + finalMsg.replace('Signed in as ', '');
            } else if (finalMsg.startsWith('Signed in successfully as ')) {
                finalMsg = 'تم تسجيل الدخول بنجاح بصفتك ' + finalMsg.replace('Signed in successfully as ', '');
            }
        }
    } else {
        if (typeof finalTitle === 'string' && toastI18n.arToEn[finalTitle]) {
            finalTitle = toastI18n.arToEn[finalTitle];
        }
        if (typeof finalMsg === 'string') {
            if (toastI18n.arToEn[finalMsg]) {
                finalMsg = toastI18n.arToEn[finalMsg];
            } else if (finalMsg.startsWith('تم تسجيل الدخول باسم ')) {
                finalMsg = 'Signed in as ' + finalMsg.replace('تم تسجيل الدخول باسم ', '');
            } else if (finalMsg.startsWith('تم تسجيل الدخول بنجاح بصفتك ')) {
                finalMsg = 'Signed in successfully as ' + finalMsg.replace('تم تسجيل الدخول بنجاح بصفتك ', '');
            }
        }
    }

    const icon = type === 'success' ? 'fa-circle-check text-emerald-500' :
                 type === 'error' ? 'fa-circle-xmark text-rose-500' :
                 type === 'warning' ? 'fa-triangle-exclamation text-amber-500' : 'fa-bell text-blue-500';

    const toast = document.createElement('div');
    toast.className = `pointer-events-auto max-w-sm w-full bg-white dark:bg-slate-800 rounded-2xl shadow-2xl border border-slate-200/90 dark:border-slate-700 p-4 flex items-start space-x-3 ${isAr ? 'space-x-reverse' : ''} toast-animate-in`;
    
    const dismiss = () => {
        toast.classList.remove('toast-animate-in');
        toast.classList.add('toast-animate-out');
        setTimeout(() => { if (toast.parentElement) toast.remove(); }, 240);
    };

    toast.innerHTML = `
        <i class="fa-solid ${icon} text-lg shrink-0 mt-0.5"></i>
        <div class="flex-1">
            <h5 class="text-xs font-bold text-slate-800 dark:text-slate-100">${escapeHtml(finalTitle)}</h5>
            <p class="text-[11px] text-slate-600 dark:text-slate-300 mt-0.5 leading-snug">${escapeHtml(finalMsg)}</p>
        </div>
        <button class="text-slate-400 hover:text-slate-600 dark:hover:text-slate-200 transition">
            <i class="fa-solid fa-xmark text-xs"></i>
        </button>
    `;

    toast.querySelector('button').onclick = dismiss;
    container.appendChild(toast);
    setTimeout(dismiss, 5000);
}

function debounce(func, wait) {
    let timeout;
    return function executedFunction(...args) {
        const later = () => {
            clearTimeout(timeout);
            func(...args);
        };
        clearTimeout(timeout);
        timeout = setTimeout(later, wait);
    };
}

function escapeHtml(str) {
    if (!str) return '';
    return String(str)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#039;');
}

